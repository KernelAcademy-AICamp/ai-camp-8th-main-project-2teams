describe("리뷰태그 추출 대량 스윕", () => {
  it("모든 MUST 케이스가 기대 태그를 포함한다", () => {
    const fails = MUST.filter(([q, t]) => !all(q).includes(t)).map(
      ([q, t]) => `MISS: "${q}" 기대 ${t} → ${JSON.stringify(all(q))}`,
    );
    if (fails.length) console.warn("\n" + fails.join("\n") + "\n");
    expect(fails).toEqual([]);
  });

  it("모든 MUST_NOT 케이스가 금지 태그를 만들지 않는다", () => {
    const fails = MUST_NOT.filter(([q, t]) => all(q).includes(t)).map(
      ([q, t]) => `FALSE+: "${q}" 금지 ${t} → ${JSON.stringify(all(q))}`,
    );
    if (fails.length) console.warn("\n" + fails.join("\n") + "\n");
    expect(fails).toEqual([]);
  });
});
