// dict(extract-review-tags) 수정 시 회귀를 잡는 그물. all()=reviewTags+excludeTags+functional.
function all(q: string): string[] {
  const r = extractReviewTags(q);
  return [...r.reviewTags, ...r.excludeTags, ...r.functional];
}

